package net.akehurst.kotlinx.utils

import net.akehurst.kotlinx.utils.HierarchicalReferenceStoreExt.resolve
import net.akehurst.kotlinx.utils.ReferenceExt.mutable
import net.akehurst.kotlinx.utils.ValueExt.mutable
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertFailsWith
import kotlin.test.assertNull
import kotlin.test.assertSame

/**
 * Tests for the ways model code generated by net.akehurst.omg uses stores, references and values:
 * factories that delegate to a store, references resolved through the root, and onChanged callbacks
 * that keep other properties up to date.
 */
class test_ReferenceUsagePatterns {

	interface Shape
	data class Circle(val name: String) : Shape
	data class Square(val name: String) : Shape

	// Like omg's generated factories: each implements the store interface by delegating to a store,
	// and passes itself (not the store) as the parent of its package factories.
	class ModelFactory(identity: Any) : HierarchicalReferenceStore<Any> by HierarchicalReferenceStoreByHashMap(null, identity) {
		val circles = PackageFactory(this, "circles")
		val squares = PackageFactory(this, "squares")
	}

	class PackageFactory(parent: HierarchicalReferenceStore<Any>, identity: Any) :
		HierarchicalReferenceStore<Any> by HierarchicalReferenceStoreByHashMap(parent, identity) {
		fun circle(id: String) = Circle(id).also { this[Circle::class, id] = it }
		fun square(id: String) = Square(id).also { this[Square::class, id] = it }
	}

	// --- stores used through delegation ---

	@Test
	fun delegating_factories_resolve_from_root_and_from_sibling() {
		val model = ModelFactory("model")
		val c1 = model.circles.circle("c1")

		assertSame(c1, model.resolve(MutableReferenceDefault<Any, Circle>("c1")))
		assertSame(c1, model.squares.resolve(MutableReferenceDefault<Any, Circle>("c1")))
		assertSame(c1, model.squares.rootReferenceStore.resolve(MutableReferenceDefault<Any, Shape>("c1")))
	}

	@Test
	fun delegating_factories_keep_one_store_per_type() {
		val model = ModelFactory("model")
		model.circles.circle("c1")
		model.circles.circle("c2") // the same factory can add more

		assertFailsWith<IllegalStateException> { model.squares.circle("c3") }
	}

	// --- resolving into a ManagedReference ---

	@Test
	fun resolve_sets_managed_reference_and_calls_onChanged_once() {
		val model = ModelFactory("model")
		val c1 = model.circles.circle("c1")
		val changes = mutableListOf<String>()
		val ref = ManagedReference<Any, Circle>(null, "ref", Circle::class) { old, new ->
			changes += "${old.reference}:${old.resolved} -> ${new.reference}:${new.resolved}"
		}
		ref.mutable.reference = "c1"

		model.resolve(ref)
		model.resolve(ref) // resolving again changes nothing

		assertSame(c1, ref.resolved)
		assertEquals(listOf("null:null -> c1:null", "c1:null -> c1:$c1"), changes)
	}

	@Test
	fun resolve_supertype_managed_reference_to_subtype_object() {
		val model = ModelFactory("model")
		val s1 = model.squares.square("s1")
		val ref = ManagedReference<Any, Shape>("s1", "ref", Shape::class)

		assertSame(s1, model.resolve(ref))
		assertSame(s1, ref.resolved)
	}

	@Test
	fun change_key_then_resolve_gives_new_object() {
		val model = ModelFactory("model")
		val c1 = model.circles.circle("c1")
		val c2 = model.circles.circle("c2")
		val ref = ManagedReference<Any, Circle>("c1", "ref", Circle::class)
		model.resolve(ref)
		assertSame(c1, ref.resolved)

		ref.mutable.reference = "c2"
		assertNull(ref.resolved) // the object for the old key is dropped
		model.resolve(ref)

		assertSame(c2, ref.resolved)
	}

	@Test
	fun resolve_reference_with_no_key_does_nothing() {
		val model = ModelFactory("model")
		model.circles.circle("c1")
		var changes = 0
		val ref = ManagedReference<Any, Circle>(null, "ref", Circle::class) { _, _ -> changes++ }

		assertNull(model.resolve(ref))
		assertNull(ref.reference)
		assertNull(ref.resolved)
		assertEquals(0, changes)
	}

	// --- ManagedValue ---

	@Test
	fun managedValue_accepts_subtype_instance() {
		val v = ManagedValue<Any?>(null, "v", Shape::class)
		val c = Circle("c")
		v.mutable.set(c)
		assertSame(c, v.get())
		assertFailsWith<IllegalArgumentException> { v.mutable.set("not a shape") }
	}

	@Test
	fun onChanged_can_update_another_managed_value() {
		// Like omg's subset upkeep: when 'part' changes, 'all' follows it if it held the old value.
		lateinit var all: ManagedValue<Shape?>
		val part = ManagedValue<Shape?>(null, "part", Shape::class) { old, new ->
			if (all.get() == old) all.mutable.set(new)
		}
		all = ManagedValue(null, "all", Shape::class)

		val c = Circle("c")
		part.mutable.set(c)
		assertSame(c, all.get())

		val s = Square("s")
		part.mutable.set(s)
		assertSame(s, all.get())

		part.mutable.set(null)
		assertNull(all.get())
	}

	@Test
	fun onChanged_setting_the_same_value_again_does_not_loop() {
		var calls = 0
		lateinit var v: ManagedValue<Shape?>
		v = ManagedValue(null, "v", Shape::class) { _, new ->
			calls++
			v.mutable.set(new) // already the current value, so nothing happens
		}
		v.mutable.set(Circle("c"))
		assertEquals(1, calls)
	}
}
