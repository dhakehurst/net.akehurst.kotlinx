package net.akehurst.kotlinx.reflect.test

import net.akehurst.kotlinx.reflect.EnumValuesFunction
import net.akehurst.kotlinx.reflect.KotlinxReflect
import kotlin.coroutines.Continuation
import kotlin.coroutines.EmptyCoroutineContext
import kotlin.coroutines.startCoroutine
import kotlin.reflect.KClass

/**
 * Registers the test classes by hand, in the same way as the code generated by the kotlinx-reflect compiler plugin.
 * (The plugin is not applied to this module's own tests.)
 */
internal fun registerTestClasses() {
    val kr = KotlinxReflect
    fun cls(qn: String, k: KClass<*>, vararg supertypes: KClass<*>, isAbstract: Boolean = false, enumValues: EnumValuesFunction? = null, obj: Any? = null) {
        kr.registerClass("net.akehurst.kotlinx.reflect.test.$qn", k, enumValues, obj)
        kr.registerClassInfo(k, isAbstract, false, supertypes.toList() + Any::class)
    }

    cls("AnObject", AnObject::class, obj = AnObject)
    @Suppress("UNCHECKED_CAST")
    cls("CR_Colour", CR_Colour::class, Enum::class, enumValues = CR_Colour::values as EnumValuesFunction)
    @Suppress("UNCHECKED_CAST")
    cls("KR_Colour", KR_Colour::class, Enum::class, enumValues = KR_Colour::values as EnumValuesFunction)
    @Suppress("UNCHECKED_CAST")
    cls("KR_Colour2", KR_Colour2::class, Enum::class, enumValues = KR_Colour2::values as EnumValuesFunction)

    cls("CR_A", CR_A::class)
    kr.registerProperty(CR_A::class, CR_A::prop1)
    kr.registerProperty(CR_A::class, CR_A::prop2)
    kr.registerProperty(CR_A::class, CR_A::prop3)
    kr.registerProperty(CR_A::class, CR_A::prop4)
    kr.registerProperty(CR_A::class, CR_A::prop5)
    kr.registerConstructor(CR_A::class, 0) { CR_A() }
    cls("CR_B", CR_B::class, CR_A::class)
    kr.registerConstructor(CR_B::class, 0) { CR_B() }
    cls("CR_C", CR_C::class, CR_B::class)
    kr.registerConstructor(CR_C::class, 0) { CR_C() }
    cls("CR_D", CR_D::class, CR_B::class)
    kr.registerConstructor(CR_D::class, 0) { CR_D() }

    cls("KR_A", KR_A::class)
    kr.registerProperty(KR_A::class, KR_A::prop1)
    kr.registerProperty(KR_A::class, KR_A::prop2)
    kr.registerProperty(KR_A::class, KR_A::prop3)
    kr.registerProperty(KR_A::class, KR_A::prop4)
    kr.registerProperty(KR_A::class, KR_A::prop5)
    kr.registerConstructor(KR_A::class, 0) { KR_A() }

    cls("OR_A", OR_A::class)
    kr.registerProperty(OR_A::class, OR_A::prop1)
    kr.registerProperty(OR_A::class, OR_A::prop2)
    kr.registerProperty(OR_A::class, OR_A::prop3)
    kr.registerProperty(OR_A::class, OR_A::prop4)
    kr.registerProperty(OR_A::class, OR_A::prop5)
    kr.registerConstructor(OR_A::class, 0) { OR_A() }
    cls("OR_B", OR_B::class, OR_A::class)
    kr.registerProperty(OR_B::class, OR_B::prop6)
    kr.registerConstructor(OR_B::class, 0) { OR_B() }

    cls("FN_Abstract", FN_Abstract::class, isAbstract = true)
    kr.registerProperty(FN_Abstract::class, FN_Abstract::name)
    kr.registerFunction(FN_Abstract::class, "greet", 1, { self, args -> (self as FN_Abstract).greet(args[0] as String) }, FN_Abstract::greet)
    cls("FN_A", FN_A::class, FN_Abstract::class)
    kr.registerProperty(FN_A::class, FN_A::name)
    kr.registerConstructor(FN_A::class, 1) { args -> FN_A(args[0] as String) }
    kr.registerFunction(FN_A::class, "add", 2, { self, args -> (self as FN_A).add(args[0] as Int, args[1] as Int) }, FN_A::add)
    kr.registerFunction(FN_A::class, "fail", 0, { self, _ -> (self as FN_A).fail() }, FN_A::fail)
    kr.registerSuspendFunction(FN_A::class, "later", 1, { self, args -> (self as FN_A).later(args[0] as Int) }, FN_A::later)
}

/** Runs a suspend block that never actually suspends, without needing kotlinx-coroutines. */
internal fun <T> runSuspend(block: suspend () -> T): T {
    var result: Result<T>? = null
    block.startCoroutine(Continuation(EmptyCoroutineContext) { result = it })
    return result!!.getOrThrow()
}
