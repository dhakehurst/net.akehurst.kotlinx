fun <T : Any> defaultValue(): T {
    return castNull()
}

fun <T : Any> createInstance(kClass: KClass<T>): T {
    return castNull()
}

/**
 * from [https://github.com/nhaarman/mockito-kotlin/blob/2.x/mockito-kotlin/src/main/kotlin/com/nhaarman/mockitokotlin2/internal/CreateInstance.kt]
 * Uses a quirk in the bytecode generated by Kotlin
 * to cast [null] to a non-null type.
 *
 * See https://youtrack.jetbrains.com/issue/KT-8135.
 */
@Suppress("UNCHECKED_CAST")
private fun <T> castNull(): T = null as T

fun <R> methodLiteral(call: KCallable<R>): Method? {
    return when (call) {
        is KFunction<R> -> call.javaMethod
        else -> null
    }
}

actual fun KFunction<*>.isSuspend(): Boolean = this.isSuspend

@Suppress("UNCHECKED_CAST")
actual fun <T : Any> proxyFor(forInterface: KClass<*>, invokeMethod: (handler: Any, proxy: Any?, callable: KCallable<*>, methodName: String, args: Array<out Any>) -> Any?): T {
    val handler = object : InvocationHandler {
        override fun invoke(proxy: Any?, method: Method?, args: Array<out Any>?): Any? {
            val args2 = args ?: emptyArray<Any>()
            //this throws an error if one of the parameters is an inline class
            // see [https://youtrack.jetbrains.com/issue/KT-34024]
            val callable = method?.kotlinFunction!!
            return invokeMethod.invoke(this, proxy, callable, method.name, args2)
        }
    }
    val proxy = Proxy.newProxyInstance(forInterface.java.classLoader, arrayOf(forInterface.java), handler)
    return proxy as T
}

internal actual fun defaultForceRegistry(): Boolean = System.getProperty("kotlinx.reflect.forceRegistry")?.toBoolean() ?: false

private val registryLock = Any()

internal actual fun withRegistryLock(block: () -> Unit) = synchronized(registryLock) { block() }

internal actual val platformBackend: ReflectionBackend? = KotlinReflectBackend

/**
 * Uses kotlin-reflect, so it also works for classes that are not registered (e.g. Java classes).
 * For Java classes (those without Kotlin metadata), getX/setX methods are treated as properties.
 */
internal object KotlinReflectBackend : ReflectionBackend {

    private fun getterName(propertyName: String) = "get${propertyName.replaceFirstChar { it.uppercaseChar() }}"
    private fun setterName(propertyName: String) = "set${propertyName.replaceFirstChar { it.uppercaseChar() }}"

    private fun memberProperty(kclass: KClass<*>, propertyName: String): KProperty1<*, *>? =
        kclass.memberProperties.firstOrNull { it.name == propertyName }

    /** A 'var' whose setter can be called from outside the class. */
    private fun isMutable(p: KProperty1<*, *>): Boolean = p is KMutableProperty1<*, *> && p.setter.visibility == KVisibility.PUBLIC

    /** A class compiled from Java (no Kotlin metadata); only these have getX/setX methods treated as properties. */
    private fun isJavaClass(kclass: KClass<*>): Boolean = !kclass.java.isAnnotationPresent(Metadata::class.java)

    private fun javaGetter(kclass: KClass<*>, propertyName: String): KFunction<*>? =
        if (!isJavaClass(kclass)) null
        else kclass.memberFunctions.firstOrNull { it.name == getterName(propertyName) && it.valueParameters.isEmpty() }

    private fun javaSetter(kclass: KClass<*>, propertyName: String): KFunction<*>? =
        if (!isJavaClass(kclass)) null
        else kclass.memberFunctions.firstOrNull { it.name == setterName(propertyName) && it.valueParameters.size == 1 }

    /** Rethrows the exception thrown by the called code, as the registry backend would. */
    private inline fun <R> unwrapped(block: () -> R): R = try {
        block()
    } catch (e: InvocationTargetException) {
        throw e.targetException
    }

    override fun qualifiedName(kclass: KClass<*>): String = kclass.qualifiedName ?: error("Class '$kclass' has no qualified name (it is local or anonymous)")
    // a sealed class cannot be instantiated either, so it counts as abstract (as in the registry)
    override fun isAbstract(kclass: KClass<*>): Boolean = kclass.isAbstract || kclass.isSealed
    override fun isInterface(kclass: KClass<*>): Boolean = kclass.java.isInterface
    override fun isEnum(kclass: KClass<*>): Boolean = kclass.java.isEnum
    override fun isObject(kclass: KClass<*>): Boolean = null != kclass.objectInstance
    override fun objectInstance(kclass: KClass<*>): Any? = kclass.objectInstance

    @Suppress("UNCHECKED_CAST")
    override fun enumValues(kclass: KClass<*>): List<Enum<*>> =
        (kclass.java.enumConstants as Array<Enum<*>>?)?.asList() ?: emptyList()

    override fun directSupertypes(kclass: KClass<*>): List<KClass<*>> =
        kclass.supertypes.mapNotNull { it.classifier as? KClass<*> }

    /** The class followed by all its supertypes, nearest first, each once (same order as the registry backend). */
    private fun hierarchy(kclass: KClass<*>): List<KClass<*>> {
        val result = mutableListOf<KClass<*>>()
        var level = listOf(kclass)
        while (level.isNotEmpty()) {
            val next = mutableListOf<KClass<*>>()
            for (k in level) {
                if (k !in result) {
                    result.add(k)
                    next.addAll(directSupertypes(k))
                }
            }
            level = next
        }
        return result
    }

    // properties inherited from the platform's own types (e.g. Enum.name) are not listed; the registry does not have them either
    private fun isPlatformType(k: KClass<*>): Boolean = k.qualifiedName?.let { it.startsWith("kotlin.") || it.startsWith("java.") } ?: false

    private val declarationOrderCache = java.util.concurrent.ConcurrentHashMap<KClass<*>, List<String>>()

    /**
     * Property names in declaration order, read from the class's Kotlin metadata
     * (kotlin-reflect lists them alphabetically; the registry keeps declaration order).
     * Empty for classes without Kotlin metadata, e.g. Java classes.
     */
    private fun declarationOrder(k: KClass<*>): List<String> = declarationOrderCache.getOrPut(k) {
        try {
            val md = k.java.getAnnotation(Metadata::class.java)
            val km = md?.let { kotlin.metadata.jvm.KotlinClassMetadata.readLenient(it) as? kotlin.metadata.jvm.KotlinClassMetadata.Class }
            km?.kmClass?.properties?.map { it.name } ?: emptyList()
        } catch (e: Exception) {
            emptyList()
        }
    }

    override fun propertyNames(kclass: KClass<*>): List<String> {
        // supertypes first, so inherited properties come before the ones a subclass adds
        return hierarchy(kclass).filter { it == kclass || !isPlatformType(it) }.reversed().flatMap { k ->
            val order = declarationOrder(k)
            val publicProps = k.declaredMemberProperties.filter { it.visibility == KVisibility.PUBLIC }.map { it.name }
                .sortedBy { order.indexOf(it).let { i -> if (i < 0) Int.MAX_VALUE else i } }
            // get methods, for java defined classes/properties
            val methProps = if (!isJavaClass(k)) emptyList() else k.declaredMemberFunctions
                .filter { it.name.startsWith("get") && it.name.length > 3 && it.valueParameters.isEmpty() && it.visibility == KVisibility.PUBLIC }
                .map { it.name.substring(3).replaceFirstChar { c -> c.lowercaseChar() } }
            publicProps + methProps
        }.distinct()
    }

    override fun memberFunctions(kclass: KClass<*>): List<KFunction<*>> =
        kclass.memberFunctions.filter { it.visibility == KVisibility.PUBLIC }

    override fun isPropertyMutable(kclass: KClass<*>, propertyName: String): Boolean? {
        val mprop = memberProperty(kclass, propertyName)
        return when {
            null != mprop -> isMutable(mprop)
            null != javaSetter(kclass, propertyName) -> true
            null != javaGetter(kclass, propertyName) -> false
            else -> null
        }
    }

    @Suppress("UNCHECKED_CAST")
    override fun getProperty(kclass: KClass<*>, self: Any, propertyName: String): Any? = unwrapped {
        val mprop = memberProperty(kclass, propertyName)
        if (null != mprop) {
            //first do null check because of bug with properties with type inline class
            val javaGetter = mprop.javaGetter
            if (null != javaGetter) {
                javaGetter.isAccessible = true
                if (null == javaGetter.invoke(self)) {
                    return@unwrapped null
                }
            }
            val prop = mprop as KProperty1<Any, *>
            prop.getter.isAccessible = true
            prop.getter.call(self)
        } else {
            val mmeth = javaGetter(kclass, propertyName) ?: ReflectErrors.propertyNotFound(kclass, propertyName)
            mmeth.isAccessible = true
            mmeth.call(self)
        }
    }

    @Suppress("UNCHECKED_CAST")
    override fun setProperty(kclass: KClass<*>, self: Any, propertyName: String, value: Any?) {
        unwrapped {
            val mprop = memberProperty(kclass, propertyName)
            if (null != mprop) {
                if (!isMutable(mprop)) ReflectErrors.propertyNotMutable(kclass, propertyName)
                val prop = mprop as KMutableProperty1<Any, Any?>
                prop.setter.isAccessible = true
                prop.setter.call(self, value)
            } else {
                //TODO: check type of parameter!
                val mmeth = javaSetter(kclass, propertyName)
                    ?: if (null != javaGetter(kclass, propertyName)) ReflectErrors.propertyNotMutable(kclass, propertyName) else ReflectErrors.propertyNotFound(kclass, propertyName)
                mmeth.isAccessible = true
                mmeth.call(self, value)
            }
        }
    }

    override fun construct(kclass: KClass<*>, args: List<Any?>): Any = unwrapped {
        val ctor = kclass.constructors.firstOrNull { c ->
            c.parameters.size == args.size && c.parameters.zip(args).all { (p, a) ->
                null == a || (p.type.classifier as? KClass<*>)?.let { it.javaObjectType.isInstance(a) || it.isInstance(a) } ?: true
            }
        } ?: ReflectErrors.constructorNotFound(kclass, args.size)
        ctor.isAccessible = true
        ctor.call(*args.toTypedArray())
    }

    private fun kotlinFunction(kclass: KClass<*>, methodName: String, arity: Int): KFunction<*>? =
        kclass.memberFunctions.firstOrNull { it.name == methodName && it.valueParameters.size == arity }

    // Kotlin mangles the JVM name of functions that take inline classes, e.g. 'foo-abc123'
    private fun mangledJavaMethod(kclass: KClass<*>, methodName: String, javaArity: Int): Method? =
        kclass.java.methods.firstOrNull { it.name.startsWith("$methodName-") && it.parameterCount == javaArity }

    // inline class values must be passed unboxed to a mangled method
    private fun unbox(meth: Method, args: List<Any?>): Array<Any?> = args.mapIndexed { index, arg ->
        val clazz = meth.parameterTypes[index]
        when {
            null == arg -> null
            clazz.isInstance(arg) -> arg
            else -> arg::class.memberProperties.first().call(arg) // there should only be one property on an inline class
        }
    }.toTypedArray()

    override fun call(kclass: KClass<*>, self: Any, methodName: String, args: List<Any?>): Any? = unwrapped {
        val kfun = kotlinFunction(kclass, methodName, args.size)
        when {
            null != kfun -> {
                if (kfun.isSuspend) ReflectErrors.isSuspend(kclass, methodName)
                kfun.isAccessible = true
                kfun.call(self, *args.toTypedArray())
            }

            else -> {
                val jmeth = kclass.java.methods.firstOrNull { it.name == methodName && it.parameterCount == args.size }
                    ?: mangledJavaMethod(kclass, methodName, args.size)
                    ?: ReflectErrors.methodNotFound(kclass, methodName, args.size)
                jmeth.invoke(self, *unbox(jmeth, args))
            }
        }
    }

    override suspend fun callSuspend(kclass: KClass<*>, self: Any, methodName: String, args: List<Any?>): Any? {
        val kfun = kotlinFunction(kclass, methodName, args.size)
        return when {
            null != kfun -> {
                if (!kfun.isSuspend) ReflectErrors.notSuspend(kclass, methodName)
                kfun.isAccessible = true
                unwrapped { kfun.callSuspend(self, *args.toTypedArray()) }
            }

            else -> {
                // the JVM method of a suspend function takes an extra 'Continuation' parameter
                val jmeth = kclass.java.methods.firstOrNull { it.name == methodName && it.parameterCount == args.size + 1 }
                    ?: mangledJavaMethod(kclass, methodName, args.size + 1)
                    ?: ReflectErrors.methodNotFound(kclass, methodName, args.size)
                val jargs = unbox(jmeth, args)
                suspendCoroutineUninterceptedOrReturn { cont ->
                    unwrapped { jmeth.invoke(self, *jargs, cont) }
                }
            }
        }
    }

    override fun isProxy(self: Any): Boolean = Proxy.isProxyClass(self.javaClass)
}
