package net.akehurst.kotlinx.collections

import net.akehurst.kotlinx.utils.ManagedReference
import net.akehurst.kotlinx.utils.Reference
import net.akehurst.kotlinx.utils.ReferenceImmutable
import kotlin.test.*

/**
 * Tests for the way model code generated by net.akehurst.omg uses managed collections of ManagedReference:
 * properties hold them in managed collections, and onChanged/onAdded/onRemoved callbacks remove references
 * using a ReferenceImmutable copy of the old reference, and keep subsetted collections in step.
 */
class test_managedReferenceUsage {

    private fun ref(key: String) = ManagedReference<Any, String>(key, "ref", String::class)

    /** The collection kinds omg uses, created as omg does: elements are ManagedReference. */
    private val kinds: Map<String, (onRemoved: (ManagedReference<Any, String>) -> Unit) -> MutableCollection<ManagedReference<Any, String>>> = mapOf(
        "Collection" to { r -> ManagedCollection("c", ManagedReference::class, onRemoved = r) },
        "List" to { r -> ManagedList("c", ManagedReference::class, onRemoved = r) },
        "Set" to { r -> ManagedSet("c", ManagedReference::class, onRemoved = r) },
        "OrderedSet" to { r -> ManagedOrderedSet("c", ManagedReference::class, onRemoved = r) },
    )

    @Test
    fun remove_with_ReferenceImmutable_removes_the_managed_reference() {
        for ((kind, create) in kinds) {
            val removed = mutableListOf<Any>()
            val c = create { removed.add(it) }
            val r1 = ref("k1")
            val r2 = ref("k2")
            c.add(r1)
            c.add(r2)

            // omg accesses the property as a collection of Reference, and removes the 'old' reference it was given
            @Suppress("UNCHECKED_CAST")
            val asReferences = c as MutableCollection<Reference<Any, String>>
            assertTrue(asReferences.remove(ReferenceImmutable("k1", null)), kind)

            assertEquals(listOf<Any>(r2), c.toList(), kind)
            assertEquals(1, removed.size, kind)
            assertSame(r1, removed[0], "$kind: onRemoved gets the stored reference")
        }
    }

    @Test
    fun remove_with_ReferenceImmutable_of_other_key_does_nothing() {
        for ((kind, create) in kinds) {
            val removed = mutableListOf<Any>()
            val c = create { removed.add(it) }
            c.add(ref("k1"))

            @Suppress("UNCHECKED_CAST")
            val asReferences = c as MutableCollection<Reference<Any, String>>
            assertFalse(asReferences.remove(ReferenceImmutable("other", null)), kind)

            assertEquals(1, c.size, kind)
            assertTrue(removed.isEmpty(), kind)
        }
    }

    @Test
    fun contains_ReferenceImmutable_with_same_key() {
        for ((kind, create) in kinds) {
            val c = create { }
            c.add(ref("k1"))
            @Suppress("UNCHECKED_CAST")
            val asReferences = c as MutableCollection<Reference<Any, String>>
            assertTrue(asReferences.contains(ReferenceImmutable("k1", null)), kind)
        }
    }

    @Test
    fun callbacks_keep_a_subsetted_collection_in_step() {
        // Like omg's subset upkeep: adding to or removing from the subset does the same to the superset.
        val all = ManagedOrderedSet<ManagedReference<Any, String>>("all", ManagedReference::class)
        val part = ManagedList<ManagedReference<Any, String>>(
            "part", ManagedReference::class,
            onAdded = { all.add(it) },
            onRemoved = { all.remove(it) }
        )
        val r1 = ref("k1")
        val r2 = ref("k2")

        part.add(r1)
        part.add(r2)
        assertEquals(listOf(r1, r2), all.toList())

        @Suppress("UNCHECKED_CAST")
        (part as MutableCollection<Reference<Any, String>>).remove(ReferenceImmutable("k1", null))
        assertEquals(listOf(r2), part.toList())
        assertEquals(listOf(r2), all.toList())

        part.clear()
        assertTrue(all.isEmpty())
    }

    @Test
    fun reference_onChanged_removes_old_reference_from_another_collection() {
        // Like omg's generated onChanged for a single reference that subsets a collection of references.
        val all = ManagedOrderedSet<ManagedReference<Any, String>>("all", ManagedReference::class)
        lateinit var single: ManagedReference<Any, String>
        single = ManagedReference(null, "single", String::class) { old, _ ->
            @Suppress("UNCHECKED_CAST")
            (all as MutableCollection<Reference<Any, String>>).remove(old)
        }
        val other = ref("k1")
        all.add(other)

        single.reference = "k1" // old reference had no key: nothing with key null is in 'all'
        assertEquals(listOf(other), all.toList())

        single.reference = "k2" // old reference had key k1: removes the reference with key k1
        assertTrue(all.isEmpty())
    }
}
