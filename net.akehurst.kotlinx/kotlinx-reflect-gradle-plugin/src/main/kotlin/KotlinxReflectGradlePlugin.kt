package net.akehurst.kotlinx.reflect.gradle.plugin

import com.google.devtools.ksp.gradle.KspAATask
import net.akehurst.kotlin.reflect.gradle.plugin.KotlinPluginInfo
import org.gradle.api.DefaultTask
import org.gradle.api.Plugin
import org.gradle.api.Project
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.model.ObjectFactory
import org.gradle.api.provider.Property
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.TaskAction
import org.jetbrains.kotlin.gradle.dsl.KotlinMultiplatformExtension
import org.jetbrains.kotlin.gradle.plugin.KotlinPlatformType
import javax.inject.Inject

open class KotlinxReflectGradlePluginExtension @Inject constructor(objects: ObjectFactory) {
    companion object {
        const val NAME = "kotlinxReflect"
    }

    /** Globs of classes to register for commonMain, e.g. `com.example.model.*`. Classes may be in this module or in dependencies. */
    val forReflectionMain = objects.listProperty(String::class.java).convention(emptyList())

    /** Extra globs of classes to register for tests (commonTest); the main ones are registered for tests too. */
    val forReflectionTest = objects.listProperty(String::class.java).convention(emptyList())
}

/**
 * Generates code that registers classes with kotlinx-reflect, using KSP:
 *  - commonMain: `<module>_commonMain.KotlinxReflectForModule`, generated by KSP's common metadata compilation.
 *  - commonTest: `<module>_commonTest.KotlinxReflectForModule`, a fixed file written by this plugin that calls
 *    an `expect fun`; KSP generates the `actual fun` once per test target (there is no commonTest metadata compilation).
 *
 * Call `KotlinxReflectForModule.registerUsedClasses()` before using reflection.
 */
class KotlinxReflectGradlePlugin : Plugin<Project> {

    companion object {
        const val KMP_PLUGIN_ID = "org.jetbrains.kotlin.multiplatform"
        const val KSP_PLUGIN_ID = "com.google.devtools.ksp"
        const val KSP_COMMON_MAIN_TASK = "kspCommonMainKotlinMetadata"

        // must match net.akehurst.kotlinx.reflect.ksp.KotlinxReflectProcessor
        const val OPTION_FOR_REFLECTION = "kotlinxReflect.forReflection"
        const val OPTION_PACKAGE = "kotlinxReflect.package"
        const val OPTION_MODE = "kotlinxReflect.mode"
        const val OBJECT_NAME = "KotlinxReflectForModule"
        const val ACTUAL_FUNCTION_NAME = "kotlinxReflectRegisterUsedClasses"

        fun moduleSafeName(project: Project) = project.name.replace(Regex("[^a-zA-Z0-9]"), "_")

        private fun String.capitalised() = replaceFirstChar { it.uppercaseChar() }
    }

    override fun apply(project: Project) {
        val extension = project.extensions.create(KotlinxReflectGradlePluginExtension.NAME, KotlinxReflectGradlePluginExtension::class.java)
        var configured = false
        project.pluginManager.withPlugin(KMP_PLUGIN_ID) {
            configured = true
            configure(project, extension)
        }
        project.afterEvaluate {
            if (!configured) {
                error("The kotlinx-reflect plugin needs the Kotlin multiplatform plugin ('$KMP_PLUGIN_ID') to be applied to project '${project.path}'")
            }
        }
    }

    private fun configure(project: Project, extension: KotlinxReflectGradlePluginExtension) {
        project.pluginManager.apply(KSP_PLUGIN_ID)
        val kotlin = project.extensions.getByType(KotlinMultiplatformExtension::class.java)

        val libraryGroup = KotlinPluginInfo.LIBRARY_GROUP
        val version = KotlinPluginInfo.PROJECT_VERSION
        val runtime = "$libraryGroup:kotlinx-reflect:$version"
        val processor = "$libraryGroup:kotlinx-reflect-ksp:$version"
        val mainPackage = "${moduleSafeName(project)}_commonMain"
        val testPackage = "${moduleSafeName(project)}_commonTest"

        // commonMain: runtime library, and the code KSP generates for it
        kotlin.sourceSets.named("commonMain") { ss ->
            ss.dependencies { implementation(runtime) }
            ss.kotlin.srcDir(project.layout.buildDirectory.dir("generated/ksp/metadata/commonMain/kotlin"))
        }

        // commonTest: the fixed file that declares the expect fun, which KSP implements per test target
        val generateTestRegistry = project.tasks.register("generateKotlinxReflectTestRegistry", GenerateTestRegistryTask::class.java) { t ->
            t.packageName.set(testPackage)
            t.outputDir.set(project.layout.buildDirectory.dir("kotlinxReflect/genSrc/commonTest"))
        }
        kotlin.sourceSets.named("commonTest") { ss ->
            ss.kotlin.srcDir(generateTestRegistry)
        }

        // The processor runs once for commonMain, and once for every compilation that includes commonTest
        // (each of those needs the 'actual fun' for the expect fun in commonTest).
        // Which compilations those are is only known once the build is configured, so it is worked out lazily.
        fun testCompilations() = kotlin.targets
            .filter { it.platformType != KotlinPlatformType.common }
            .flatMap { it.compilations }
            .filter { c -> c.allKotlinSourceSets.any { it.name == "commonTest" } }

        // KSP names its configurations after the source set, e.g. 'kspJvmTest', 'kspAndroidUnitTestDebug'
        fun isTestKspConfiguration(name: String) = testCompilations().any { name == "ksp" + it.defaultSourceSet.name.capitalised() }

        // KSP names its tasks after the compilation and target, e.g. 'kspTestKotlinJvm', 'kspDebugUnitTestKotlinAndroid'
        fun isTestKspTask(name: String) = testCompilations().any { c ->
            val compilation = if (c.name == "main") "" else c.name.capitalised()
            name == "ksp${compilation}Kotlin${c.target.name.capitalised()}"
        }

        project.dependencies.add("kspCommonMainMetadata", processor)
        project.configurations.matching { it.name.startsWith("ksp") && it.name != "kspCommonMainMetadata" }.configureEach { cfg ->
            // evaluated when the dependencies are first read, after the build is configured
            cfg.dependencies.addAllLater(project.provider {
                if (isTestKspConfiguration(cfg.name)) listOf(project.dependencies.create(processor)) else emptyList()
            })
        }

        // options are set per KSP task, because main and test need different values
        val mainGlobs = extension.forReflectionMain.map { it.distinct().joinToString(",") }
        val testGlobs = extension.forReflectionMain.zip(extension.forReflectionTest) { m, t -> (m + t).distinct().joinToString(",") }
        project.tasks.withType(KspAATask::class.java).configureEach { task ->
            val isTest = project.provider { isTestKspTask(task.name) }
            val options = task.kspConfig.processorOptions
            options.put(OPTION_MODE, isTest.map { if (it) "actual" else "object" })
            options.put(OPTION_FOR_REFLECTION, isTest.flatMap { if (it) testGlobs else mainGlobs })
            options.put(OPTION_PACKAGE, isTest.map { if (it) testPackage else mainPackage })
            task.dependsOn(isTest.map { if (it) listOf(generateTestRegistry) else emptyList() })
        }

        // everything that reads commonMain sources needs the generated code first
        val kspCommonMain = project.tasks.matching { it.name == KSP_COMMON_MAIN_TASK }
        project.tasks.matching { task ->
            task.name != KSP_COMMON_MAIN_TASK && (
                    task is org.jetbrains.kotlin.gradle.tasks.KotlinCompilationTask<*>
                            || task.name.startsWith("ksp")
                            || task.name.endsWith("sourcesJar", ignoreCase = true)
                    )
        }.configureEach { task ->
            task.dependsOn(kspCommonMain)
        }
    }
}

/** Writes the commonTest `KotlinxReflectForModule` object, which calls the `expect fun` that KSP implements per test target. */
@CacheableTask
abstract class GenerateTestRegistryTask : DefaultTask() {

    @get:Input
    abstract val packageName: Property<String>

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val pkg = packageName.get()
        val dir = outputDir.get().asFile.resolve(pkg.replace('.', '/'))
        dir.mkdirs()
        dir.resolve("${KotlinxReflectGradlePlugin.OBJECT_NAME}.kt").writeText(
            """
            |// Generated by the kotlinx-reflect Gradle plugin. Do not edit.
            |// KSP generates the 'actual fun ${KotlinxReflectGradlePlugin.ACTUAL_FUNCTION_NAME}()' once per test target.
            |package $pkg
            |
            |object ${KotlinxReflectGradlePlugin.OBJECT_NAME} : net.akehurst.kotlinx.reflect.KotlinxReflectModuleRegistry {
            |    /** Registers the classes with KotlinxReflect. Safe to call more than once. */
            |    fun registerUsedClasses() = ${KotlinxReflectGradlePlugin.ACTUAL_FUNCTION_NAME}()
            |
            |    override fun registerClasses() = registerUsedClasses()
            |}
            |
            |internal expect fun ${KotlinxReflectGradlePlugin.ACTUAL_FUNCTION_NAME}()
            |""".trimMargin()
        )
    }
}
